void TModelWaterManager::garbageCollect()
{
	u16 nextFreeSlot = 0;
	for (int i = 0; i < mParticleCount; ++i) {
		if (mParticleLifetimeSOA[i] <= 0.0f)
			continue;

		if (i != nextFreeSlot) {
			mParticleLifetimeSOA[nextFreeSlot] = mParticleLifetimeSOA[i];
			mParticleFlagSOA[nextFreeSlot]     = mParticleFlagSOA[i];
			mParticleAttackSOA[nextFreeSlot]   = mParticleAttackSOA[i];
			mParticlePositionSOA[nextFreeSlot] = mParticlePositionSOA[i];
			mParticleVelocitySOA[nextFreeSlot] = mParticleVelocitySOA[i];
			mParticleSizeSOA[nextFreeSlot]     = mParticleSizeSOA[i];
			mParticleTypeSOA[nextFreeSlot]     = mParticleTypeSOA[i];
			unk2514[nextFreeSlot]              = unk2514[i];
			unk2914[nextFreeSlot]              = unk2914[i];
		}

		++nextFreeSlot;
	}

	mParticleCount = nextFreeSlot;
}

void TModelWaterManager::move()
{
	// TODO: 96.4%. Control flow, members and constants now follow retail.
	// Left: the frame is 0x70 short (0x278 vs 0x2e8); retail keeps
	// gWaterManagerPlaneInfo and the splash-argument temporary in saved
	// registers from the prologue; retail reads `local_248->mActor` and
	// `local_b4->mActor` through an `lwzu` address it reloads after the
	// mStaticHitActor stores (getActor(), inline cast and const_cast are
	// inert); and the merge distance fuses `x*x + y*y` into an fmadds
	// where TVec3::length() keeps three fmuls.
	f32 fVar1 = unk5E08 * unk5E08;
	for (int i = 0; i < mParticleCount; ++i) {
		if (unk2514[i] != nullptr) {
			mStaticHitActor.mPosition = mParticlePositionSOA[i];
			mStaticHitActor.mParticleIndex = i;

			if (unk2514[i]->receiveMessage(&mStaticHitActor,
			                               HIT_MESSAGE_SPRAYED_BY_WATER)) {
				splashSound(mParticlePositionSOA[i], mParticleSizeSOA[i]);

				if (MsRandF() < unk5D88[8])
					gpSplashManager->newSplash(mParticlePositionSOA[i], 5.0f);

				mParticleLifetimeSOA[i] = 0.0f;
				continue;
			}
		}

		JGeometry::TVec3<f32> thing;
		thing.sub(SMS_GetMarioPos(), mParticlePositionSOA[i]);

		if (thing.x * thing.x + thing.z * thing.z > fVar1) {
			mParticleLifetimeSOA[i] = 0.0f;
			continue;
		}

		f32 horVelSq
		    = mParticleVelocitySOA[i].x * mParticleVelocitySOA[i].x
		      + mParticleVelocitySOA[i].z * mParticleVelocitySOA[i].z;
		if (horVelSq > mParticleSizeSOA[i] * mParticleSizeSOA[i]) {
			f32 horLen = std::sqrtf(horVelSq);

			mParticleVelocitySOA[i].x
			    *= (mParticleSizeSOA[i] - 0.1f) * (1.0f / horLen);
			mParticleVelocitySOA[i].z
			    *= (mParticleSizeSOA[i] - 0.1f) * (1.0f / horLen);
		}

		switch (mParticleFlagSOA[i] & 0xf) {
		case 1:
			mParticleVelocitySOA[i].y += getWPGravity(i);

			mParticlePositionSOA[i].x += mParticleVelocitySOA[i].x;
			mParticlePositionSOA[i].y += mParticleVelocitySOA[i].y;
			mParticlePositionSOA[i].z += mParticleVelocitySOA[i].z;
			break;

		case 2: {
			mParticleVelocitySOA[i].x
			    = mParticleVelocitySOA[i].x * getPlaneFriction(unk2914[i])
			      + unk2914[i]->getNormal().x;
			mParticleVelocitySOA[i].y = getWPGravity(i);
			mParticleVelocitySOA[i].z
			    = mParticleVelocitySOA[i].z * getPlaneFriction(unk2914[i])
			      + unk2914[i]->getNormal().z;

			mParticlePositionSOA[i].x += mParticleVelocitySOA[i].x;
			mParticlePositionSOA[i].y += mParticleVelocitySOA[i].y;
			mParticlePositionSOA[i].z += mParticleVelocitySOA[i].z;
			break;
		}

		case 3:
			mParticlePositionSOA[i].y += getPlaneFall(unk2914[i]);
			break;
		}
	}

	const TBGCheckData* local_248 = 0;
	f32 f31;

	for (int i = 0; i < mParticleCount; ++i) {
		if (mParticleVelocitySOA[i].y < 0.0f) {
			f31 = gpMap->checkGroundIgnoreWaterThrough(
			    mParticlePositionSOA[i].x,
			    mParticlePositionSOA[i].y - mParticleVelocitySOA[i].y,
			    mParticlePositionSOA[i].z, &local_248);

			if (local_248->isLegal() && !(1.0f + f31 < mParticlePositionSOA[i].y)) {
				if (local_248->isWaterSurface()) {
					if (MsRandF() < unk5D88[11])
						SMS_EmitRippleTiny(&mParticlePositionSOA[i]);

					mParticleLifetimeSOA[i] = 0.0f;

					gpMSound->startSoundSet(MSD_SE_WT_INTO_WATER,
					                        &mParticlePositionSOA[i], 0.0f, 0.0f,
					                        0.0f, 0, 4);
					continue;
				}

				if (local_248->isPool()) {
					mParticleLifetimeSOA[i] = 0.0f;
					if (MsRandF() < unk5D88[11])
						SMS_EmitRippleTiny(&mParticlePositionSOA[i]);

					splashSound(mParticlePositionSOA[i], mParticleSizeSOA[i]);
					continue;
				}

				mParticlePositionSOA[i].y = f31 - getWPGravity(i);

				if (getFlagBottom4Bits(i) == 3) {
					mParticleLifetimeSOA[i] = 0.0f;
					continue;
				}

				if (getFlagBottom4Bits(i) == 1) {
					if (MsRandF() < unk5D88[9])
						gpSplashManager->newSplash(mParticlePositionSOA[i], 5.0f);

					splashSound(mParticlePositionSOA[i], mParticleSizeSOA[i]);

					mParticleSizeSOA[i]
					    *= mWaterParticleTypes[mParticleTypeSOA[i]]->mMagnify.get();
					f32 fVar1;
					if (gpCamera->isLButtonCamera())
						fVar1 = unk5D88[1];
					else
						fVar1 = unk5D88[0];

					if (MsRandF() < fVar1) {
						setFlagBottom4Bits(i, 2);
					} else {
						mParticleLifetimeSOA[i] = 0.0f;
						continue;
					}
				}

				unk2914[i] = local_248;
				if (local_248->mActor != nullptr) {
					mStaticHitActor.mPosition = mParticlePositionSOA[i];
					mStaticHitActor.mParticleIndex = i;
					THitActor* hit            = (THitActor*)local_248->mActor;
					if (hit->receiveMessage(&mStaticHitActor,
					                        HIT_MESSAGE_SPRAYED_BY_WATER))
						mParticleLifetimeSOA[i] = 0.0f;
				}

				continue;
			}
		}

		static TBGWallCheckRecord wcheck;

		wcheck.set(mParticlePositionSOA[i].x,
		           mParticlePositionSOA[i].y + mParticleSizeSOA[i] * 0.5f,
		           mParticlePositionSOA[i].z, mParticleSizeSOA[i], 1,
		           TBGWallCheckRecord::IGNORE_WATER_THROUGH);

		if (gpMap->isTouchedWallsAndMoveXZ(&wcheck)) {
			const TBGCheckData* r27 = wcheck.mResultWalls[0];

			if (getFlagBottom4Bits(i) == 2) {
				mParticleLifetimeSOA[i] = 0.0f;
				continue;
			} else {
				if (local_248 != nullptr && local_248->isLegal()
				    && mParticlePositionSOA[i].y
				           < mParticleSizeSOA[i]
				                     * mWaterParticleTypes
				                           [mParticleTypeSOA[i]]
				                               ->mMagnify.get()
				                 + f31) {
					mParticleLifetimeSOA[i] = 0.0f;
					continue;
				} else {
					if (r27->mActor != nullptr) {
						mStaticHitActor.mPosition = mParticlePositionSOA[i];
						mStaticHitActor.mParticleIndex = i;
						THitActor* hit            = (THitActor*)r27->mActor;
						hit->receiveMessage(&mStaticHitActor,
						                    HIT_MESSAGE_SPRAYED_BY_WATER);
					}

					// Unnamed `b * k`, not a copy plus an in-place scale:
					// only the former puts TVec3::scale(f32) at inline
					// depth 4 (copy ctor 1, operator* 2, operator*= 3),
					// where the ROM `bl`s it. Retail's two copies here
					// are operator*'s by-value operand and its result.
					mParticlePositionSOA[i]
					    -= r27->getNormal()
					       * (r27->mPlaneDistance
					          + mParticlePositionSOA[i].dot(r27->getNormal()));

					if (getFlagBottom4Bits(i) == 1) {
						JGeometry::TVec3<f32> local_1A4
						    = mParticlePositionSOA[i]
						      + r27->getNormal() * mParticleSizeSOA[i];
						if (MsRandF() < unk5D88[10])
							gpSplashManager->newSplash(local_1A4, 5.0f);

						splashSound(mParticlePositionSOA[i],
						            mParticleSizeSOA[i]);

						mParticleSizeSOA[i]
						    *= mWaterParticleTypes[mParticleTypeSOA[i]]
						           ->mMagnify.get();
						if (MsRandF() < unk5D88[2]) {
							setFlagBottom4Bits(i, 3);
						} else {
							mParticleLifetimeSOA[i] = 0.0f;
							continue;
						}
					}
				}
			}

			unk2914[i] = r27;
		} else {
			if (mParticleVelocitySOA[i].y >= 0.0f) {
				const TBGCheckData* local_b4 = nullptr;
				f32 dVar24 = gpMap->checkRoofIgnoreWaterThrough(
				    mParticlePositionSOA[i].x, mParticlePositionSOA[i].y,
				    mParticlePositionSOA[i].z, &local_b4);
				if (local_b4) {
					if (local_b4->mActor != nullptr) {
						mStaticHitActor.mPosition = mParticlePositionSOA[i];
						mStaticHitActor.mParticleIndex = i;
						THitActor* hit = (THitActor*)local_b4->mActor;
						hit->receiveMessage(&mStaticHitActor,
						                    HIT_MESSAGE_SPRAYED_BY_WATER);
					}

					if (mParticlePositionSOA[i].y + mParticleSizeSOA[i]
					    > dVar24) {
						mParticlePositionSOA[i].y
						    = dVar24 - mParticleSizeSOA[i];
						mParticleVelocitySOA[i].x = 0.0f;
						mParticleVelocitySOA[i].y = 0.0f;
						mParticleVelocitySOA[i].z = 0.0f;

						setFlagBottom4Bits(i, 1);
						continue;
					}
				}
			}

			setFlagBottom4Bits(i, 1);
		}
	}

	int r20 = -1;
	int r26 = -1;
	for (int i = 0; i < mParticleCount; ++i) {
		switch (mParticleFlagSOA[i] & 0xf) {
		case 1:
			mParticleLifetimeSOA[i] -= 1.0f;
			break;

		case 2: {
			if (mParticleLifetimeSOA[i] > unk5D68)
				mParticleLifetimeSOA[i] = unk5D68;
			gpMSound->startSoundSet(MSD_SE_PO_WT_DRY_UP,
			                        &mParticlePositionSOA[i], 0, 0.0f, 0, 0, 4);

			splashGround(i); // TODO: probably wrong inline

			if (unk5D60 & 0x40) {
				if (r20 < 0) {
					r20 = i;
				} else {
					JGeometry::TVec3<f32> kek = mParticlePositionSOA[i] - mParticlePositionSOA[r20];

					f32 max = unk5D88[6]
					          * (mParticleSizeSOA[i] + mParticleSizeSOA[r20]);

					if (kek.length() < max) {

						mParticleSizeSOA[r20]     = mParticleSizeSOA[i];
						mParticleLifetimeSOA[r20] = mParticleLifetimeSOA[i];
						mParticleLifetimeSOA[i]   = 0.0f;
					} else {
						r20 = i;
					}
				}
			}
			break;
		}
		case 3:
			if (mParticleLifetimeSOA[i] > unk5D6C)
				mParticleLifetimeSOA[i] = unk5D6C;

			splashWall(i); // TODO: probably wrong inline

			if (unk5D60 & 0x40) {
				if (r26 < 0) {
					r26 = i;
				} else {
					JGeometry::TVec3<f32> kek = mParticlePositionSOA[i] - mParticlePositionSOA[r26];

					f32 max = unk5D88[6]
					          * (mParticleSizeSOA[i] + mParticleSizeSOA[r26]);

					// We're merging particles here I guess?
					if (kek.length() < max) {
						mParticleSizeSOA[r26]     = mParticleSizeSOA[i];
						mParticleLifetimeSOA[r26] = mParticleLifetimeSOA[i];
						mParticleLifetimeSOA[i]   = 0.0f;
					} else {
						r26 = i;
					}
				}
			}
			break;
		}
	}

	garbageCollect();
}

void TModelWaterManager::calcWorldMinMax()
{
	if (mParticleCount == 0) {
		unk5D70 = *gpMarioPos;
		unk5D7C = *gpMarioPos;

		unk5D70.x -= 1.0f;
		unk5D70.y -= 1.0f;
		unk5D70.z -= 1.0f;

		unk5D7C.x += 1.0f;
		unk5D7C.y += 1.0f;
		unk5D7C.z += 1.0f;
		return;
	}

	f32 minX = mParticlePositionSOA[0].x - 1.0f;
	f32 minY = mParticlePositionSOA[0].y - 1.0f;
	f32 minZ = mParticlePositionSOA[0].z - 1.0f;
	f32 maxX = 1.0f + mParticlePositionSOA[0].x;
	f32 maxY = 1.0f + mParticlePositionSOA[0].y;
	f32 maxZ = 1.0f + mParticlePositionSOA[0].z;

	for (int i = 1; i < mParticleCount; i++) {
		if (minX > mParticlePositionSOA[i].x)
			minX = mParticlePositionSOA[i].x;
		if (minY > mParticlePositionSOA[i].y)
			minY = mParticlePositionSOA[i].y;
		if (minZ > mParticlePositionSOA[i].z)
			minZ = mParticlePositionSOA[i].z;
		if (maxX < mParticlePositionSOA[i].x)
			maxX = mParticlePositionSOA[i].x;
		if (maxY < mParticlePositionSOA[i].y)
			maxY = mParticlePositionSOA[i].y;
		if (maxZ < mParticlePositionSOA[i].z)
			maxZ = mParticlePositionSOA[i].z;
	}

	unk5D70.x = minX - 200.0f;
	unk5D70.y = minY - 200.0f;
	unk5D70.z = minZ - 200.0f;

	unk5D7C.x = 200.0f + maxX;
	unk5D7C.y = 200.0f + maxY;
	unk5D7C.z = 200.0f + maxZ;
}

// TODO: instruction-identical and the frame matches at 0xe0, but every local
// sits 12 bytes low: retail has one more 12-byte inline-expansion temporary
// below `viewVel` (temporaries grow up from 0xc), so `vtx` lands at 0x54 there
// and 0x48 here. No candidate for that expansion found.
void TModelWaterManager::calcDrawVtx(MtxPtr viewMtx)
{
	unk5D30->reset();

	for (int i = 0; i < mParticleCount; i++) {
		JGeometry::TVec3<f32> vtx[4];

		if (getFlagBottom4Bits(i) != 1)
			continue;

		f32 fadeTime = unk5D88[7];
		u8 type      = mParticleTypeSOA[i];
		f32 life     = mParticleLifetimeSOA[i];
		if (!(life < mWaterParticleTypes[type]->mAlive.get() - fadeTime))
			continue;

		JGeometry::TVec3<f32> viewPos;
		MTXMultVec(viewMtx, &mParticlePositionSOA[i], &viewPos);
		if (viewPos.z > 0.0f)
			continue;
		if (viewPos.z < -unk5D28)
			continue;

		JGeometry::TVec3<f32> viewVel;
		MTXMultVecSR(viewMtx, &mParticleVelocitySOA[i], &viewVel);

		f32 extension = mWaterParticleTypes[mParticleTypeSOA[i]]
		                    ->mExtension.get();
		viewVel.x *= extension;
		viewVel.y *= extension;
		viewVel.z *= extension;

		f32 speedSq = viewVel.x * viewVel.x + viewVel.y * viewVel.y;
		f32 radius  = 1.414f * (0.5f * mParticleSizeSOA[i]);

		if (speedSq > 1.0f) {
			f32 stretch = (1.0f / MsSqrtf(speedSq)) * radius;
			f32 sx      = viewVel.x * stretch;
			f32 sy      = viewVel.y * stretch;
			f32 px      = sy;
			f32 py      = -sx;

			vtx[0].x = viewPos.x + sx + viewVel.x * unk5D18;
			vtx[0].y = viewPos.y + sy + viewVel.y * unk5D18;
			vtx[0].z = viewPos.z;
			vtx[1].x = viewPos.x + px;
			vtx[1].y = viewPos.y + py;
			vtx[1].z = viewPos.z;
			vtx[2].x = viewPos.x - sx - viewVel.x * unk5D18;
			vtx[2].y = viewPos.y - sy - viewVel.y * unk5D18;
			vtx[2].z = viewPos.z;
			vtx[3].x = viewPos.x - px;
			vtx[3].y = viewPos.y - py;
			vtx[3].z = viewPos.z;
		} else {
			vtx[0].x = viewPos.x - radius;
			vtx[0].y = viewPos.y + radius;
			vtx[0].z = viewPos.z;
			vtx[1].x = viewPos.x + radius;
			vtx[1].y = viewPos.y + radius;
			vtx[1].z = viewPos.z;
			vtx[2].x = viewPos.x + radius;
			vtx[2].y = viewPos.y - radius;
			vtx[2].z = viewPos.z;
			vtx[3].x = viewPos.x - radius;
			vtx[3].y = viewPos.y - radius;
			vtx[3].z = viewPos.z;
		}

		unk5D30->request(vtx);
	}

	unk5D30->setEnd();
}

// TODO: 97.2%, register allocation only. The three rows are one loop (the
// unrolled form costs two extra saved FPRs); the ROM still keeps b*dir.y in
// f30 and each row's [0] in a volatile, where we give [0] a saved FPR. Every
// order of the four row locals and moving each setup local to the front or
// back were measured; this order is the best.
void TModelWaterManager::calcVMMtxGround(MtxPtr param_1, f32 param_2,
                                         const JGeometry::TVec3<f32>& param_3,
                                         const JGeometry::TVec3<f32>& param_4,
                                         MtxPtr param_5)
{
	f32 fVar6  = param_2 * param_4.x;
	f32 fVar7  = param_2 * param_4.y;
	f32 fVar11 = 2.0f * param_4.y + param_3.y;
	f32 fVar12 = -fVar6;

	f32 fVar10 = 2.0f * param_4.x + param_3.x;
	f32 fVar8  = param_2 * param_4.z;
	f32 fVar9  = 2.0f * param_4.z + param_3.z;
	f32 fVar13 = -fVar8;

	for (int i = 0; i < 3; ++i) {
		f32 fVar1     = param_1[i][1];
		f32 fVar2     = param_1[i][2];
		f32 fVar4     = param_1[i][3];
		f32 fVar3     = param_1[i][0];
		param_5[i][0] = fVar3 * fVar7 + fVar1 * fVar12;
		param_5[i][1] = fVar3 * fVar6 + fVar1 * fVar7 + fVar2 * fVar8;
		param_5[i][2] = fVar1 * fVar13 + fVar2 * fVar7;
		param_5[i][3]
		    = fVar4 + (fVar3 * fVar10 + fVar1 * fVar11 + fVar2 * fVar9);
	}
}

// TODO: 97.7%, register allocation only; the rows are one loop, as in
// calcVMMtxGround. Every order of the four row locals was measured.
void TModelWaterManager::calcVMMtxWall(MtxPtr param_1, f32 scale,
                                       const JGeometry::TVec3<f32>& param_3,
                                       const JGeometry::TVec3<f32>& param_4,
                                       MtxPtr param_5)
{
	f32 fVar7  = scale * param_4.x;
	f32 fVar4  = param_3.y;
	f32 fVar8  = scale * param_4.z;
	f32 fVar11 = -fVar7;
	f32 fVar10 = 2.0f * param_4.x + param_3.x;
	f32 fVar9  = 2.0f * param_4.z + param_3.z;

	for (int i = 0; i < 3; ++i) {
		f32 fVar1     = param_1[i][2];
		f32 fVar2     = param_1[i][1];
		f32 fVar3     = param_1[i][0];
		f32 fVar5     = param_1[i][3];
		param_5[i][0] = fVar3 * fVar8 + fVar1 * fVar11;
		param_5[i][1] = fVar2 * scale;
		param_5[i][2] = fVar3 * fVar7 + fVar1 * fVar8;
		param_5[i][3]
		    = fVar5 + (fVar3 * fVar10 + fVar2 * fVar4 + fVar1 * fVar9);
	}
}

// Binding level over a raw member read, worth +16 of low region in
// TModelWaterManager::calcVMAll (batch 127).
static inline u16 ModelWaterManagerParticleCount(const TModelWaterManager* p)
{
	u16 particleCount = p->mParticleCount;
	return particleCount;
}

void TModelWaterManager::calcVMAll(MtxPtr param_1)
{
	for (int i = 0; i < ModelWaterManagerParticleCount(this); ++i) {
		if ((mParticleFlagSOA[i] & 0xf) != 2)
			continue;

		f32 f = mParticleSizeSOA[i]
		        * ((1.0f - unk5D88[5]) * (mParticleLifetimeSOA[i] / unk5D68)
		           + unk5D88[5]);
		calcVMMtxGround(param_1, f, mParticlePositionSOA[i],
		                unk2914[i]->getNormal(), unk2D14[i]);
	}

	for (int i = 0; i < ModelWaterManagerParticleCount(this); ++i) {
		if ((mParticleFlagSOA[i] & 0xf) != 3)
			continue;

		f32 f = mParticleSizeSOA[i]
		        * ((1.0f - unk5D88[5]) * (mParticleLifetimeSOA[i] / unk5D6C)
		           + unk5D88[5]);
		matan(unk2914[i]->getNormal().z, unk2914[i]->getNormal().x);
		calcVMMtxWall(param_1, f, mParticlePositionSOA[i],
		              unk2914[i]->getNormal(), unk2D14[i]);
	}
}

